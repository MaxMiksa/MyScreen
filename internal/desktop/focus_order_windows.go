//go:build windows

package desktop

import (
	"errors"
	"unsafe"

	"golang.org/x/sys/windows"
)

var (
	setWinEventHook   = u32.NewProc("SetWinEventHook")
	unhookWinEvent    = u32.NewProc("UnhookWinEvent")
	getDesktopWindow  = u32.NewProc("GetDesktopWindow")
	getWindowInOrder  = u32.NewProc("GetWindow")
	maskOrderCallback = windows.NewCallback(onMaskOrderEvent)
)

const (
	eventObjectShow        = 0x8002
	eventObjectReorder     = 0x8004
	objIDClient            = -4
	gwHwndPrev             = 3
	computerUseCursorClass = "CodexComputerUseCursorOverlay"
)

func (c *Controller) startMaskOrderWatch() error {
	if c.maskOrderHook != 0 {
		return nil
	}
	c.maskDesktop, _, _ = getDesktopWindow.Call()
	// Out-of-context (same message thread); skip events generated by MyScreen.
	h, _, err := setWinEventHook.Call(eventObjectShow, eventObjectReorder, 0, maskOrderCallback, 0, 0, 2)
	if h == 0 {
		return winError("SetWinEventHook(focus overlay)", err)
	}
	c.maskOrderHook = h
	return nil
}

func (c *Controller) stopMaskOrderWatch() error {
	c.maskOrderDirty = false
	if c.maskOrderHook == 0 {
		return nil
	}
	if err := boolCall(unhookWinEvent, c.maskOrderHook); err != nil {
		return err
	}
	c.maskOrderHook, c.maskDesktop = 0, 0
	return nil
}

func onMaskOrderEvent(hook uintptr, event uint32, hwnd uintptr, object, child int32, _, _ uint32) uintptr {
	if hwnd == 0 || child != 0 {
		return 0
	}
	owner, ok := threadOwners.Load(windows.GetCurrentThreadId())
	if !ok {
		return 0
	}
	c := owner.(*Controller)
	if c.maskOrderHook == hook && !c.closing.Load() && !c.maskOrderDirty &&
		(event == eventObjectReorder && hwnd == c.maskDesktop && object == objIDClient ||
			event == eventObjectShow && object == 0 && isComputerUseCursorWindow(hwnd)) {
		// Coalesce a burst of accessibility events; only the controller loop
		// may change the order of its own windows.
		c.maskOrderDirty = true
	}
	return 0
}

func isComputerUseCursorWindow(hwnd uintptr) bool {
	var class [64]uint16
	n, _, _ := focusGetClassNameW.Call(hwnd, uintptr(unsafe.Pointer(&class[0])), uintptr(len(class)))
	if n == 0 || windows.UTF16ToString(class[:n]) != computerUseCursorClass {
		return false
	}
	style, _, _ := focusGetExStyle.Call(hwnd, ^uintptr(19))               // GWL_EXSTYLE
	return uint32(style)&(focusPassiveOverlay|8) == focusPassiveOverlay|8 // WS_EX_TOPMOST
}

func computerUseAboveMask(mask uintptr) bool {
	visible, _, _ := focusIsWindowVisible.Call(mask)
	var bounds Rect
	if visible == 0 || boolCall(focusGetWindowRect, mask, uintptr(unsafe.Pointer(&bounds))) != nil {
		return false
	}
	// Only windows above the known topmost mask matter. Bound traversal even
	// if another process is rapidly destroying/reordering those windows.
	for h, i := mask, 0; i < 128; i++ {
		h, _, _ = getWindowInOrder.Call(h, gwHwndPrev)
		if h == 0 {
			break
		}
		if !isComputerUseCursorWindow(h) {
			continue
		}
		var overlay Rect
		visible, _, _ := focusIsWindowVisible.Call(h)
		if visible != 0 && boolCall(focusGetWindowRect, h, uintptr(unsafe.Pointer(&overlay))) == nil &&
			bounds.Left < overlay.Right && overlay.Left < bounds.Right && bounds.Top < overlay.Bottom && overlay.Top < bounds.Bottom {
			return true
		}
	}
	return false
}

func (c *Controller) restoreMaskOrder() error {
	if len(c.masks) == 0 || !isConsole() {
		return nil
	}
	var result error
	for _, mask := range c.masks {
		if computerUseAboveMask(mask) {
			// No activate/move/resize/show. Never set attributes or position on
			// the Computer Use window: its primary-monitor cues stay intact.
			result = errors.Join(result, boolCall(setWindowPos, mask, ^uintptr(0), 0, 0, 0, 0, 0x0013))
		}
	}
	return result
}
